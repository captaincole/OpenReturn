import { table } from "../lib/markdown";
import type { CrowdingRun } from "./crowding";
import { TOP_K, type CaseScore, type LawCase } from "./score";

export interface ModeRun {
  mode: string;
  scores: CaseScore[];
}

const count = (scores: CaseScore[], hit: (score: CaseScore) => boolean | null) => {
  const scored = scores.filter((score) => hit(score) !== null);
  const share = scored.length ? Math.round((100 * scored.filter(hit).length) / scored.length) : 0;
  return `${scored.filter(hit).length}/${scored.length} (${share}%)`;
};

const missed = (score: CaseScore) => !score.sectionHit || score.pathHit === false;

function summary(runs: ModeRun[]): string {
  return table(
    ["Mode", "Section hit", "Path hit"],
    runs.map((run) => [
      run.mode,
      count(run.scores, (score) => score.sectionHit),
      count(run.scores, (score) => score.pathHit),
    ]),
  );
}

function missLines(cases: LawCase[], run: ModeRun, level = "###"): string[] {
  const byId = new Map(cases.map((testCase) => [testCase.id, testCase]));
  const misses = run.scores.filter(missed);
  if (misses.length === 0) return [`${level} ${run.mode}`, "", "No misses."];
  return [
    `${level} ${run.mode} (${misses.length})`,
    "",
    ...misses.map((score) => {
      const testCase = byId.get(score.id)!;
      const what = score.sectionHit
        ? `path ${testCase.expectPath}`
        : `section ${testCase.expect.join(" or ")}`;
      const top = score.top.slice(0, 3).join("; ") || "no hits";
      return `- \`${score.id}\` missed ${what}. Top 3: ${top}`;
    }),
  ];
}

export const UNREVIEWED =
  "Not reviewed by a person yet: agents wrote and checked these cases. Use the scores for development only.";

export interface ReportInput {
  cases: LawCase[];
  runs: ModeRun[];
  crowding: CrowdingRun[];
  regCases: LawCase[];
  regRuns: ModeRun[];
  date: string;
}

const listOrNone = (ids: string[]) =>
  ids.length ? ids.map((id) => `\`${id}\``).join(", ") : "none";

function crowdingLines(crowding: CrowdingRun[]): string[] {
  return [
    "## The Code cases on the whole library",
    "",
    `The same Code cases with no source filter, so the regulations compete for the top ${TOP_K}. **Crowded out** counts the statute hits of the statute-only top ${TOP_K} that are not in the whole library's top ${TOP_K}, over all cases.`,
    "",
    table(
      ["Mode", "Statute hits", "Crowded out", "Regulation hits", "Section lost", "Path lost"],
      crowding.map((run) => [
        run.mode,
        String(run.statuteHits),
        `${run.crowdedOut} (${Math.round((100 * run.crowdedOut) / Math.max(1, run.statuteHits))}%)`,
        String(run.regulationHits),
        listOrNone(run.lostSection),
        listOrNone(run.lostPath),
      ]),
    ),
    "",
  ];
}

function regulationLines(regCases: LawCase[], regRuns: ModeRun[]): string[] {
  return [
    "## Regulation cases",
    "",
    UNREVIEWED,
    "",
    `Questions the statute leaves to the regulations, in \`canon/evals/law/regCases.json\`, searched on the whole library (searchLaw's default). A hit counts as above; the sections are regulation sections.`,
    "",
    summary(regRuns),
    "",
    "### Misses",
    "",
    ...regRuns.flatMap((run) => [...missLines(regCases, run, "####"), ""]),
  ];
}

export function renderReport(input: ReportInput): string {
  const { cases, runs, date } = input;
  return [
    "# Law search eval",
    "",
    `_Generated by \`canon/evals/law\` on ${date}. Do not edit by hand._`,
    "",
    `Each case runs its queries (the statute's words, as an agent writes them after it read the IRS instructions) through the law search, ${TOP_K} hits per query, and merges the hits by best rank. No model call: the vector leg embeds the queries with the local Ollama model. The cases are in \`canon/evals/law/cases.json\`. The Code cases search the statute only (source "statute"); the sections below run them on the whole library, and run the regulation cases.`,
    "",
    `- **Section hit:** one of the top ${TOP_K} merged hits is in a section the case expects.`,
    `- **Path hit:** for a case with \`expectPath\`, one of the top ${TOP_K} hits is that subdivision, is inside it, or is the parent block that prints it.`,
    "",
    "## Summary",
    "",
    summary(runs),
    "",
    "## Misses",
    "",
    "A miss lists the top 3 citations the case got.",
    "",
    ...runs.flatMap((run) => [...missLines(cases, run), ""]),
    ...crowdingLines(input.crowding),
    ...regulationLines(input.regCases, input.regRuns),
    "## Run it",
    "",
    "From the repo root, with law.db installed (`npm run corpus -- law sync`) and Ollama running:",
    "",
    "```bash",
    "npm run evals:law",
    "```",
    "",
  ].join("\n");
}
