/*
 * Renders the review-judge eval as docs/evals/review.md, and the review
 * flow's row in the eval overview (docs/evals/README.md, lib/overview.ts). Run directly to combine saved runs (a later file replaces a
 * model's rows for the cases it ran):
 *
 *   npx tsx evals/review/report.ts <results.json>…   (from canon)
 */
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { avg, table } from "../lib/markdown";
import { forDisplay, type EvalModel } from "../lib/models";
import { publishOverview } from "../lib/overview";
import { groundedOk, reviewFlowScores, verdictOk } from "./flow";

export interface ReviewResult {
  model: string;
  case: string;
  run: number;
  expectedVerdict: string;
  verdict: string;
  citedAuthority: boolean;
  retrievedAuthority: boolean;
  cited: string[];
  invalidCitations: string[];
  iterations: number;
  latencyMs: number;
  reason: string;
}

export interface ReviewRun {
  models: EvalModel[];
  results: ReviewResult[];
}

const REPO = path.resolve(__dirname, "../../..");
const OUT = path.join(REPO, "docs/evals/review.md");

const count = (rs: ReviewResult[], pred: (r: ReviewResult) => boolean) =>
  `${rs.filter(pred).length}/${rs.length}`;
const shouldGround = (rs: ReviewResult[]) => rs.filter((r) => r.expectedVerdict === "accurate");

function summaryTable(models: EvalModel[], results: ReviewResult[]): string {
  const rows = models.map((m) => {
    const mine = results.filter((r) => r.model === m.label);
    return [
      m.label,
      String(m.runs),
      count(mine, verdictOk),
      count(shouldGround(mine), groundedOk),
      count(mine, (r) => r.retrievedAuthority),
      count(mine, (r) => r.invalidCitations.length > 0),
      count(mine, (r) => r.verdict === "review_failed"),
      `${(avg(mine.map((r) => r.latencyMs)) / 1000).toFixed(0)}s`,
    ];
  });
  return table(
    [
      "Model",
      "Runs per case",
      "Verdict correct",
      "Grounded (accurate cases)",
      "Authority retrieved",
      "Cited unretrieved ids",
      "Review failed",
      "Avg time",
    ],
    rows,
  );
}

function caseTable(models: EvalModel[], results: ReviewResult[]): string {
  const cases = [...new Set(results.map((r) => r.case))];
  const rows = cases.map((c) => {
    const expected = results.find((r) => r.case === c)!.expectedVerdict;
    return [
      c,
      expected,
      ...models.map((m) => {
        const rs = results.filter((r) => r.model === m.label && r.case === c);
        if (!rs.length) return "—";
        const verdicts = [...new Set(rs.map((r) => r.verdict))].join(", ");
        const cited =
          expected === "accurate" ? ` · cited ${count(rs, (r) => r.citedAuthority)}` : "";
        return `${count(rs, verdictOk)} (${verdicts})${cited} · retrieved ${count(rs, (r) => r.retrievedAuthority)}`;
      }),
    ];
  });
  return table(["Case", "Expected", ...models.map((m) => m.label)], rows);
}

export function renderReport(models: EvalModel[], results: ReviewResult[]): string {
  return [
    "# Review-judge eval",
    `_Generated by \`canon/evals/review\` on ${new Date().toISOString().slice(0, 10)}. Do not edit by hand._`,
    "Each case seeds facts and one AI decision, then runs the production ground pipeline (query formulator, risk assessor, rule judge, hybrid retrieval over the IRS corpus). Every decision has a correct version and a wrong one. The cases and their expected authority are in `canon/evals/review/cases.ts`.",
    "- **Verdict correct:** the workflow's verdict matches the expected one.\n- **Grounded:** on a correct decision, the judge says `accurate` and cites at least one labeled block for each rule.\n- **Authority retrieved:** the gather step found a labeled block at all. A miss here is a retrieval problem, not a judge problem.\n- **Cited unretrieved ids:** the judge cited an id the run never retrieved (a fact key or a made-up block id). The workflow should only store retrieved blocks.",
    `Models: ${models.map((m) => `${m.label} (\`${m.id}\`)`).join(", ")}.`,
    "## Summary",
    summaryTable(models, results),
    "## By case",
    caseTable(models, results),
    "## Run it",
    "From `canon`, with Ollama running (retrieval embeds queries locally):\n\n```bash\nnpx tsx --env-file=.env.development evals/review/run.ts <model-substring> [--runs=N]\n```",
  ].join("\n\n");
}

/*
 * Merge runs: a later run replaces a model's results for the cases it ran,
 * so one case can be rerun on its own. Write the doc and the overview;
 * return the doc's repo path.
 */
export function publishReport(runs: ReviewRun[]): string {
  const models = new Map<string, EvalModel>();
  const results = new Map<string, ReviewResult[]>();
  for (const run of runs) {
    for (const model of run.models) models.set(model.label, model);
    const fresh = new Map<string, ReviewResult[]>();
    for (const r of run.results) {
      const key = `${r.model}\u0000${r.case}`;
      fresh.set(key, [...(fresh.get(key) ?? []), r]);
    }
    for (const [key, rs] of fresh) results.set(key, rs);
  }
  const all = [...results.values()].flat();
  const used = [...models.values()].filter((m) => all.some((r) => r.model === m.label));
  const shown = forDisplay(used, all);
  writeFileSync(OUT, renderReport(shown.models, shown.results) + "\n");
  publishOverview(reviewFlowScores(shown.models, shown.results));
  return path.relative(REPO, OUT);
}

if (require.main === module) {
  const runs = process.argv.slice(2).map((f) => JSON.parse(readFileSync(f, "utf8")) as ReviewRun);
  console.log(publishReport(runs));
}
