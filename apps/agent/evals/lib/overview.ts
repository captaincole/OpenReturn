/*
 * The eval overview, docs/evals/README.md: one number per model, which
 * breaks down into one number per flow (ingest, review, ask), which breaks down
 * into capabilities. Each flow's report keeps the raw numbers.
 *
 * A flow's report writes its scores to docs/evals/scores/<flow>.json when
 * it publishes, then calls publishOverview, which renders every flow found
 * there. The overall score is the mean of a model's flow scores, so it
 * shows only for models that ran every flow.
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { pct, table } from "./markdown";

export type Flow = "ingest" | "review" | "ask";

export interface ModelScores {
  label: string;
  id: string;
  score: number;
  /* Capability name → score. A model with no case for a capability has no entry. */
  capabilities: Record<string, number>;
  /* Set when the model ran only part of the flow's cases, e.g. "12/23 documents". */
  partial?: string;
}

export interface FlowScores {
  flow: Flow;
  title: string;
  /* How the flow score is computed: one or two sentences. */
  definition: string;
  report: string;
  capabilities: string[];
  models: ModelScores[];
}

const REPO = path.resolve(__dirname, "../../../..");
const DIR = path.join(REPO, "docs/evals");
const FLOWS: Flow[] = ["ingest", "review", "ask"];
const scoresFile = (flow: Flow) => path.join(DIR, "scores", `${flow}.json`);

const cell = (m: ModelScores | undefined) =>
  m ? `${pct(m.score)}${m.partial ? ` (${m.partial})` : ""}` : "—";

/* Each model's overall score: the mean of its flow scores, when it ran every flow in full. */
function overallRows(flows: FlowScores[]) {
  const labels = [...new Set(flows.flatMap((f) => f.models.map((m) => m.label)))];
  const rows = labels.map((label) => {
    const mine = flows.map((f) => f.models.find((m) => m.label === label));
    const complete = mine.every((m) => m && !m.partial);
    const overall = complete ? mine.reduce((s, m) => s + m!.score, 0) / mine.length : undefined;
    return { label, overall, cells: mine.map(cell) };
  });
  return rows.sort((a, b) => (b.overall ?? -1) - (a.overall ?? -1));
}

function headline(flows: FlowScores[]): string {
  const rows = overallRows(flows);
  return table(
    ["Model", "**Overall**", ...flows.map((f) => f.title)],
    rows.map((r) => [r.label, `**${r.overall === undefined ? "—" : pct(r.overall)}**`, ...r.cells]),
  );
}

/* One flow's table, its rows in the headline's order. */
function flowSection(f: FlowScores, order: string[]): string {
  const sorted = [...f.models].sort((a, b) => order.indexOf(a.label) - order.indexOf(b.label));
  const rows = sorted.map((m) => [
    m.label,
    `**${cell(m)}**`,
    ...f.capabilities.map((c) => (c in m.capabilities ? pct(m.capabilities[c]) : "—")),
  ]);
  return [
    `## ${f.title}`,
    `${f.definition} Raw numbers: [${f.report}](${f.report}).`,
    table(["Model", `**${f.title}**`, ...f.capabilities], rows),
  ].join("\n\n");
}

export function renderOverview(flows: FlowScores[]): string {
  const order = overallRows(flows).map((r) => r.label);
  return [
    "# Model evals",
    `_Generated by the model evals (\`apps/agent/evals\`, \`canon/evals\`) on ${new Date().toISOString().slice(0, 10)}. Do not edit by hand._`,
    "One number per model: the mean of its flow scores (shown only when the model ran every flow). Each flow score breaks down into capabilities below, and each flow's report has the raw numbers. All scores are 0–100%; higher is better.",
    headline(flows),
    ...flows.map((f) => flowSection(f, order)),
  ].join("\n\n");
}

/* Save one flow's scores and re-render the overview from every saved flow. */
export function publishOverview(scores: FlowScores): string {
  mkdirSync(path.dirname(scoresFile(scores.flow)), { recursive: true });
  writeFileSync(scoresFile(scores.flow), JSON.stringify(scores, null, 2) + "\n");
  const flows = FLOWS.filter((f) => existsSync(scoresFile(f))).map(
    (f) => JSON.parse(readFileSync(scoresFile(f), "utf8")) as FlowScores,
  );
  const out = path.join(DIR, "README.md");
  writeFileSync(out, renderOverview(flows) + "\n");
  return path.relative(REPO, out);
}
