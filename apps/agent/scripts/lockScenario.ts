/*
 * Lock a scenario's expected values to the engine's current output.
 *
 *   npx tsx scripts/lockScenario.ts --scenario=jordan
 *
 * Rewrites tests/scenarios/<name>/expected.ts: engineFields become every
 * non-zero numeric line the engine fills, labelled from the catalog. A
 * zero is kept only where expected.ts already asserts it: a filed-return
 * comparison treats blank and 0 as equal, so it never verifies a zero.
 * Form 8949 rows are locked too, though the comparison kit skips them (a
 * preparer may combine lots); they are verified only through the
 * Schedule D totals.
 * renderedText / renderedBlank / renderedChecked are kept as they are.
 *
 * Run it only after the engine's output for this scenario is verified,
 * e.g. against a filed return with the comparison kit
 * (scripts/compareFiled). From then on, any change to a locked line
 * fails the test suite until someone verifies it and locks again.
 */

import { writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { parseArgs } from "node:util";
import { evaluateScenario } from "../src/engine/index.js";
import { catalog } from "../src/engine/registry.js";
import { decisionsWithPreparerStyle } from "../tests/helpers/preparer.js";
import type { ExpectedResults, Scenario } from "../tests/types.js";

function lockedFields(
  s: Scenario,
  current: (formId: string) => ExpectedResults,
): Record<string, Record<string, number>> {
  const evaluated = evaluateScenario({
    filing: { id: s.name, taxYear: s.taxYear },
    facts: s.facts,
    decisions: decisionsWithPreparerStyle(s),
  });
  const out: Record<string, Record<string, number>> = {};
  for (const { formId } of s.forms) {
    const form = evaluated.forms.get(formId);
    if (!form?.mustFile.ok || form.mustFile.value !== true) continue;
    const fields: Record<string, number> = {};
    const assertedZero = (id: string) => current(formId).engineFields[id] === 0;
    for (const f of form.fields) {
      if (f.valueType !== "numeric" || !f.result.ok || typeof f.result.value !== "number") continue;
      if (f.result.value !== 0 || assertedZero(f.fieldId)) fields[f.fieldId] = f.result.value;
    }
    if (Object.keys(fields).length > 0) out[formId] = fields;
  }
  return out;
}

const label = (fieldId: string) =>
  (catalog.getField(fieldId)?.label ?? "").replace(/\s+/g, " ").trim().slice(0, 90);

function formBlock(
  formId: string,
  fields: Record<string, number>,
  kept: ExpectedResults,
): string[] {
  const lines = [`  ${JSON.stringify(formId)}: {`, "    engineFields: {"];
  for (const [id, value] of Object.entries(fields)) {
    lines.push(`      // ${label(id)}`, `      ${JSON.stringify(id)}: ${value},`);
  }
  lines.push("    },");
  for (const key of ["renderedText", "renderedBlank", "renderedChecked"] as const) {
    const v = kept[key];
    if (Array.isArray(v) ? v.length > 0 : Object.keys(v).length > 0) {
      lines.push(`    ${key}: ${JSON.stringify(v)},`);
    }
  }
  lines.push("  },");
  return lines;
}

/* Header for an unverified scenario: no answer key behind the values. */
const UNVERIFIED_NOTE = [
  " *",
  " * UNVERIFIED: no CPA return or filed-return check stands behind these",
  " * values. They are engine output, checked by hand, so a failure means",
  ' * "the engine changed", not "the engine is wrong".',
];

function render(
  s: Scenario,
  fnName: string,
  locked: Record<string, Record<string, number>>,
  current: (formId: string) => ExpectedResults,
): string {
  const today = new Date().toISOString().slice(0, 10);
  const head = [
    "/*",
    ` * ${s.name} — LOCKED expected values (${today}).`,
    ...(s.verification === "unverified" ? UNVERIFIED_NOTE : []),
    " *",
    " * GENERATED by scripts/lockScenario.ts from the engine's output. Do not",
    " * edit engineFields by hand: verify a change (e.g. against a filed",
    " * return with scripts/compareFiled), then run the script again.",
    " * renderedText / renderedBlank / renderedChecked are hand-written and",
    " * carried over by the script.",
    " */",
    "",
    'import type { ExpectedResults } from "../../types.js";',
    "",
    "const EXPECTED: Record<string, Partial<ExpectedResults>> = {",
  ];
  const body = Object.entries(locked).flatMap(([formId, fields]) =>
    formBlock(formId, fields, current(formId)),
  );
  const tail = [
    "};",
    "",
    `export function ${fnName}(formId: string): ExpectedResults {`,
    "  const e = EXPECTED[formId] ?? {};",
    "  return {",
    "    engineFields: e.engineFields ?? {},",
    "    renderedText: e.renderedText ?? {},",
    "    renderedBlank: e.renderedBlank ?? [],",
    "    renderedChecked: e.renderedChecked ?? [],",
    "  };",
    "}",
    "",
  ];
  return [...head, ...body, ...tail].join("\n");
}

async function main(): Promise<void> {
  const { values } = parseArgs({ options: { scenario: { type: "string" } } });
  const name = values.scenario;
  if (!name) throw new Error("usage: tsx scripts/lockScenario.ts --scenario=<name>");
  const dir = resolve(process.cwd(), "tests/scenarios", name);
  const index = (await import(resolve(dir, "index.ts"))) as Record<string, Scenario>;
  const expected = (await import(resolve(dir, "expected.ts"))) as Record<string, unknown>;
  const s = index[`${name}Scenario`];
  const fnName = `${name}Expected`;
  const current = expected[fnName] as ((formId: string) => ExpectedResults) | undefined;
  if (!s || !current) throw new Error(`need ${name}Scenario and ${fnName} exports in ${dir}`);
  const locked = lockedFields(s, current);
  writeFileSync(resolve(dir, "expected.ts"), render(s, fnName, locked, current));
  const count = Object.values(locked).reduce((n, f) => n + Object.keys(f).length, 0);
  console.log(
    `Locked ${count} line(s) across ${Object.keys(locked).length} form(s) in ${dir}/expected.ts`,
  );
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
