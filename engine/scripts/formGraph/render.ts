/* Pure: the form graph in, the text of docs/form-graph.md out. */

import type { FieldNode, FormGraph, FormNode } from "./graph.js";

/* The fields listed for each form. The JSON file has all of them. */
const FIELDS_PER_FORM = 10;

const INTRO = `# Form graph

_Generated by \`npm run form-graph\`. Do not edit by hand. \`form-graph.json\` holds the same data, with every field._

This report shows which form reads which form, and which fields no scenario has checked. A scenario is one test taxpayer in \`engine/tests/scenarios\`: the golden suite computes the return and compares each form with a checked copy. Use the report to choose the next form or field to work on.

Each field has one state:

- **Verified:** a scenario with an answer key gives the field a value.
- **Locked:** only scenarios with no answer key give the field a value. The value is the engine's own output, checked by hand.
- **Not run:** the field has a rule, and no scenario gives it a value.
- **Unsupported:** the engine leaves the field blank.

**Feeds** is the count of fields that read a field, directly or through other fields. A field that feeds many fields is worth more work.

The reads come from two places. A scenario run records each field that a rule reads, but only on the path that the scenario takes. The form code names the fields of other forms that it reads, on every path, but not which rule reads them. A read between forms that only shared code makes, on a path that no scenario takes, is missing.

A form also depends on another form when both use the same input (Schedule D and the sales on Form 8949). The graph does not show that: it shows only a field that reads a field.`;

const nameOf = (graph: FormGraph, formId: string): string =>
  graph.forms.find((form) => form.formId === formId)?.displayName ?? formId;

const namesOf = (graph: FormGraph, formIds: string[]): string =>
  formIds.length === 0 ? "none" : formIds.map((formId) => nameOf(graph, formId)).join(", ");

const notChecked = (form: FormNode): number =>
  form.states.locked + form.states.not_run + form.states.unsupported;

function summaryTable(graph: FormGraph): string {
  const rows = graph.forms.map(
    (form) =>
      `| ${form.displayName} | ${form.jurisdiction} | ${form.scenarios.length} | ${form.fieldCount} | ${form.states.verified} | ${form.states.locked} | ${form.states.not_run} | ${form.states.unsupported} | ${form.reads.length} | ${form.feeds.length} |`,
  );
  return [
    "| Form | Jurisdiction | Scenarios | Fields | Verified | Locked | Not run | Unsupported | Reads forms | Feeds forms |",
    "| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |",
    ...rows,
  ].join("\n");
}

const STATE_TEXT: Record<FieldNode["state"], string> = {
  verified: "verified",
  locked: "locked",
  not_run: "not run",
  unsupported: "unsupported",
};

/* The part of the id after the form: "form-1040.line.11b" is "line.11b". */
const shortIdOf = (field: FieldNode): string => field.fieldId.slice(field.formId.length + 1);

/* A pipe in a label ends a table cell. */
const cellText = (text: string): string => text.split("|").join("/");

function fieldRows(graph: FormGraph, fields: FieldNode[]): string[] {
  return fields.map(
    (field) =>
      `| \`${shortIdOf(field)}\` | ${cellText(field.label)} | ${STATE_TEXT[field.state]} | ${field.feeds} | ${namesOf(graph, field.feedsForms)} |`,
  );
}

function formSection(graph: FormGraph, form: FormNode): string {
  const open = graph.fields
    .filter((field) => field.formId === form.formId && field.state !== "verified")
    .sort((left, right) => right.feeds - left.feeds);
  const shown = open.filter((field) => field.feeds > 0).slice(0, FIELDS_PER_FORM);
  const lines = [
    `### ${form.displayName}`,
    "",
    `- Reads: ${namesOf(graph, form.reads)}`,
    `- Feeds: ${namesOf(graph, form.feeds)}`,
    `- Fields: ${form.states.verified} of ${form.fieldCount} verified, ${notChecked(form)} not checked`,
  ];
  if (shown.length > 0) {
    lines.push(
      "",
      "| Field | Label | State | Feeds | Read by forms |",
      "| --- | --- | --- | --- | --- |",
      ...fieldRows(graph, shown),
    );
  }
  const rest = open.length - shown.length;
  if (rest > 0) lines.push("", `${rest} more not checked, each of which feeds fewer fields.`);
  return lines.join("\n");
}

function loopSection(graph: FormGraph): string {
  if (graph.loops.length === 0)
    return "No field reads itself through other fields in a scenario run.";
  return graph.loops.map((loop) => `- ${loop.map((id) => `\`${id}\``).join(", ")}`).join("\n");
}

export function renderFormGraph(graph: FormGraph): string {
  return [
    INTRO,
    "## Summary",
    `The golden suite ran ${graph.scenarios} scenarios.`,
    summaryTable(graph),
    "## By form",
    "For each form: the fields that are not verified and that other fields read, by the count of fields they feed.",
    ...graph.forms.map((form) => formSection(graph, form)),
    "## Loops",
    loopSection(graph),
    "",
  ].join("\n\n");
}
