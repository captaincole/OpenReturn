import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { pct, table } from "./markdown";

export type Flow = "ingest" | "review" | "ask";

export interface ModelScores {
  label: string;
  id: string;
  score: number;
  capabilities: Record<string, number>;
  partial?: string;
}

export interface FlowScores {
  flow: Flow;
  title: string;
  definition: string;
  report: string;
  capabilities: string[];
  models: ModelScores[];
}

const REPO = path.resolve(__dirname, "../../..");
const DIR = path.join(REPO, "docs/evals");
const FLOWS: Flow[] = ["ingest", "review", "ask"];
const scoresFile = (flow: Flow) => path.join(DIR, "scores", `${flow}.json`);

const cell = (scores: ModelScores | undefined) =>
  scores ? `${pct(scores.score)}${scores.partial ? ` (${scores.partial})` : ""}` : "—";

function overallRows(flows: FlowScores[]) {
  const labels = [...new Set(flows.flatMap((flow) => flow.models.map((model) => model.label)))];
  const rows = labels.map((label) => {
    const mine = flows.map((flow) => flow.models.find((model) => model.label === label));
    const complete = mine.every((scores) => scores && !scores.partial);
    const overall = complete
      ? mine.reduce((total, scores) => total + scores!.score, 0) / mine.length
      : undefined;
    return { label, overall, cells: mine.map(cell) };
  });
  return rows.sort((left, right) => (right.overall ?? -1) - (left.overall ?? -1));
}

function headline(flows: FlowScores[]): string {
  const rows = overallRows(flows);
  return table(
    ["Model", "**Overall**", ...flows.map((flow) => flow.title)],
    rows.map((row) => [
      row.label,
      `**${row.overall === undefined ? "—" : pct(row.overall)}**`,
      ...row.cells,
    ]),
  );
}

function flowSection(flowScores: FlowScores, order: string[]): string {
  const sorted = [...flowScores.models].sort(
    (left, right) => order.indexOf(left.label) - order.indexOf(right.label),
  );
  const rows = sorted.map((scores) => [
    scores.label,
    `**${cell(scores)}**`,
    ...flowScores.capabilities.map((capability) =>
      capability in scores.capabilities ? pct(scores.capabilities[capability]) : "—",
    ),
  ]);
  return [
    `## ${flowScores.title}`,
    `${flowScores.definition} Raw numbers: [${flowScores.report}](${flowScores.report}).`,
    table(["Model", `**${flowScores.title}**`, ...flowScores.capabilities], rows),
  ].join("\n\n");
}

export function renderOverview(flows: FlowScores[]): string {
  const order = overallRows(flows).map((row) => row.label);
  return [
    "# Model evals",
    `_Generated by the model evals (\`cade/evals\`, \`canon/evals\`) on ${new Date().toISOString().slice(0, 10)}. Do not edit by hand._`,
    "One number per model: the mean of its flow scores (shown only when the model ran every flow). Each flow score breaks down into capabilities below, and each flow's report has the raw numbers. All scores are 0–100%; higher is better.",
    headline(flows),
    ...flows.map((flow) => flowSection(flow, order)),
  ].join("\n\n");
}

export function publishOverview(scores: FlowScores): string {
  mkdirSync(path.dirname(scoresFile(scores.flow)), { recursive: true });
  writeFileSync(scoresFile(scores.flow), JSON.stringify(scores, null, 2) + "\n");
  const flows = FLOWS.filter((flow) => existsSync(scoresFile(flow))).map(
    (flow) => JSON.parse(readFileSync(scoresFile(flow), "utf8")) as FlowScores,
  );
  const out = path.join(DIR, "README.md");
  writeFileSync(out, renderOverview(flows) + "\n");
  return path.relative(REPO, out);
}
