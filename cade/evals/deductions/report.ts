/*
 * Combines saved runs; a later file replaces a model's rows for the cases it ran:
 *   npx tsx evals/deductions/report.ts <results.json>…   (from cade)
 */
import type { ItemId } from "@openreturn/engine";
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { OUTCOMES, type Outcome } from "../../src/mastra/deductions/openDoor";
import { avg, table } from "../lib/markdown";
import { forDisplay, type EvalModel } from "../lib/models";
import { publishOverview } from "../lib/overview";
import { CASES } from "./cases";
import { deductionsFlowScores, failure, OUTCOME_TITLES, passed } from "./flow";

export interface DoorResult {
  model: string;
  case: string;
  run: number;
  expected: Outcome;
  expectedItem?: ItemId;
  /** Each named-expense decision the run wrote. */
  recorded: { slug: string; outcome: string; item?: string }[];
  /** Each fact or assumption the run wrote that is not the door's own: an amount. */
  amountKeys: string[];
  /** The run wrote the fact that says nothing else is left. */
  closedDoor: boolean;
  latencyMs: number;
  replyText: string;
  error?: string;
}

export interface DoorRun {
  models: EvalModel[];
  results: DoorResult[];
}

const REPO = path.resolve(__dirname, "../../..");
const OUT = path.join(REPO, "docs/evals/deductions.md");

const count = (results: DoorResult[]) => `${results.filter(passed).length}/${results.length}`;

function summaryTable(models: EvalModel[], results: DoorResult[]): string {
  const rows = models.map((model) => {
    const mine = results.filter((result) => result.model === model.label);
    return [
      model.label,
      String(model.runs),
      count(mine),
      ...OUTCOMES.map((outcome) => count(mine.filter((result) => result.expected === outcome))),
      `${(avg(mine.map((result) => result.latencyMs)) / 1000).toFixed(0)}s`,
    ];
  });
  return table(
    [
      "Model",
      "Runs per case",
      "Correct",
      ...OUTCOMES.map((outcome) => OUTCOME_TITLES[outcome]),
      "Avg time",
    ],
    rows,
  );
}

const expectedCell = (result: DoorResult) =>
  result.expectedItem ? `${result.expected} (${result.expectedItem})` : result.expected;

function modelCell(runs: DoorResult[]): string {
  if (!runs.length) return "—";
  const failures = [...new Set(runs.flatMap((result) => failure(result) ?? []))];
  return failures.length ? `${count(runs)} (${failures.join("; ")})` : count(runs);
}

function caseTable(models: EvalModel[], results: DoorResult[]): string {
  const cases = [...new Set(results.map((result) => result.case))];
  const rows = cases.map((name) => {
    const says = CASES.find((testCase) => testCase.name === name)?.says ?? "";
    return [
      name,
      says,
      expectedCell(results.find((result) => result.case === name)!),
      ...models.map((model) =>
        modelCell(results.filter((result) => result.model === model.label && result.case === name)),
      ),
    ];
  });
  return table(
    ["Case", "The taxpayer says", "Expected", ...models.map((model) => model.label)],
    rows,
  );
}

export function renderReport(models: EvalModel[], results: DoorResult[]): string {
  return [
    "# Deductions eval",
    `_Generated by \`cade/evals/deductions\` on ${new Date().toISOString().slice(0, 10)}. Do not edit by hand._`,
    "Each case is one expense a taxpayer names at the open door of the deductions conversation. The run starts from a filing with a no to every life question, so the open door is the step to take. The model gets the conversation's instructions and tools and the taxpayer's one message. The cases and the reason for each label are in `cade/evals/deductions/cases.ts`.",
    "- **Correct:** the model recorded the expense, each record has the expected outcome (and the expected item, when the expense counts here), the run wrote no amount, and the door stayed open.\n- **counts_here:** a deduction item covers the expense.\n- **counts_elsewhere:** it is not an itemized deduction, and it may count in a different place on the return.\n- **does_not_count:** it is not deductible anywhere on the return.\n- **not_sure:** it may count and no item covers it. The CPA gets it.",
    `Models: ${models.map((model) => `${model.label} (\`${model.id}\`)`).join(", ")}.`,
    "## Summary",
    summaryTable(models, results),
    "## By case",
    caseTable(models, results),
    "## Run it",
    "From `cade`, with Ollama running for the local models:\n\n```bash\nnpx tsx --env-file=.env evals/deductions/run.ts --full [model…] [--runs=N]\n```\n\nThe lite tier is `npm run evals:lite` from the repo root.",
  ].join("\n\n");
}

export function publishReport(runs: DoorRun[]): string {
  const models = new Map<string, EvalModel>();
  const results = new Map<string, DoorResult[]>();
  for (const run of runs) {
    for (const model of run.models) models.set(model.label, model);
    const fresh = new Map<string, DoorResult[]>();
    for (const result of run.results) {
      const key = `${result.model}\u0000${result.case}`;
      fresh.set(key, [...(fresh.get(key) ?? []), result]);
    }
    for (const [key, rows] of fresh) results.set(key, rows);
  }
  const all = [...results.values()].flat();
  const used = [...models.values()].filter((model) =>
    all.some((result) => result.model === model.label),
  );
  const shown = forDisplay(used, all);
  writeFileSync(OUT, renderReport(shown.models, shown.results) + "\n");
  publishOverview(deductionsFlowScores(shown.models, shown.results));
  return path.relative(REPO, OUT);
}

if (require.main === module) {
  const runs = process.argv
    .slice(2)
    .map((file) => JSON.parse(readFileSync(file, "utf8")) as DoorRun);
  console.log(publishReport(runs));
}
