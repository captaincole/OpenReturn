/*
 * Zero-config first boot: generate .env.development for both apps when
 * missing, with the .data paths filled in as absolute paths for THIS
 * clone. Module-relative defaults resolve differently inside Mastra's
 * bundled output than in tsx scripts. Pinned absolute paths keep every
 * entry point on the same files.
 *
 * Runs automatically via the root predev and predev:web hooks.
 * Idempotent: an existing .env.development is never touched. Delete the
 * file to regenerate it.
 */

import { existsSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = dirname(dirname(fileURLToPath(import.meta.url)));
const DATA = join(ROOT, "apps", "agent", ".data");
/* Canon owns the reference corpus; Cade reads the same file in-process for now. */
const CANON_DATA = join(ROOT, "canon", ".data");

const canonEnvPath = join(ROOT, "canon", ".env.development");
const agentEnvPath = join(ROOT, "apps", "agent", ".env.development");
const webEnvPath = join(ROOT, "apps", "web", ".env.development");

let wrote = false;

if (!existsSync(canonEnvPath)) {
  writeFileSync(
    canonEnvPath,
    `# Generated by scripts/bootstrap-env.mjs — edit freely; delete to regenerate.

# REQUIRED — the judges' model (Ask The Tax Code, grounding). No in-code
# default on purpose. For a local server: JUDGE_MODEL=ollama/gemma4:31b and
# JUDGE_MODEL_URL=http://localhost:11434/v1.
ANTHROPIC_API_KEY=
JUDGE_MODEL=anthropic/claude-haiku-5-5

# Semantic retrieval embeds locally via Ollama (\`ollama pull embeddinggemma-2\`).
# Without Ollama running, search falls back to keyword (FTS) matching.
# EMBEDDINGS_MODEL=ollama/embeddinggemma-2
# EMBEDDINGS_MODEL_URL=http://localhost:11434

# Local data files. corpus.db is the library (\`npm run corpus -- fetch\`).
CORPUS_DB_PATH=${CANON_DATA}/corpus.db
MASTRA_DB_PATH=${CANON_DATA}/mastra.db
`,
  );
  console.log(`[bootstrap] wrote ${canonEnvPath}`);
  wrote = true;
}

if (!existsSync(agentEnvPath)) {
  writeFileSync(
    agentEnvPath,
    `# Generated by scripts/bootstrap-env.mjs — edit freely; delete to regenerate.

# REQUIRED — the one key the app cannot run without.
ANTHROPIC_API_KEY=

# REQUIRED — which model powers each role. No in-code defaults on purpose.
# To use a local/self-hosted OpenAI-compatible server (Ollama, LM Studio,
# vLLM, …) set e.g. CADE_MODEL=ollama/qwen3-vl:8b and
# CADE_MODEL_URL=http://localhost:11434/v1 (same pattern for JUDGE_*).
CADE_MODEL=anthropic/claude-sonnet-4-6
JUDGE_MODEL=anthropic/claude-haiku-5-5

# Semantic retrieval (RAG) embeds locally via Ollama — install from
# https://ollama.com and run \`ollama pull embeddinggemma-2\`. Without Ollama
# running, reference search falls back to keyword (FTS) matching.
# Defaults shown; uncomment to override.
# EMBEDDINGS_MODEL=ollama/embeddinggemma-2
# EMBEDDINGS_MODEL_URL=http://localhost:11434

# Local data files. corpus.db is Canon's; Cade reads it in-process for now.
CORPUS_DB_PATH=${CANON_DATA}/corpus.db
APP_DB_PATH=${DATA}/app.db
MASTRA_DB_PATH=${DATA}/mastra.db
DOCUMENTS_PATH=${DATA}/documents
`,
  );
  console.log(`[bootstrap] wrote ${agentEnvPath}`);
  wrote = true;
}

if (!existsSync(webEnvPath)) {
  writeFileSync(
    webEnvPath,
    `# Generated by scripts/bootstrap-env.mjs — edit freely; delete to regenerate.
APP_DB_PATH=${DATA}/app.db
DOCUMENTS_PATH=${DATA}/documents
`,
  );
  console.log(`[bootstrap] wrote ${webEnvPath}`);
  wrote = true;
}

if (wrote) {
  console.log(
    "[bootstrap] first run: set ANTHROPIC_API_KEY in canon/.env.development and" +
      " apps/agent/.env.development, then `npm run corpus -- fetch` for the prebuilt reference corpus.",
  );
}
